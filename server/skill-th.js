/** ผสมชื่อ/คำอธิบายไทยเข้ากับข้อมูลสกิล — ไม่มีในตาราง = คงของอังกฤษไว้ */
function decorate(skill) {
  const t = TH[skill.id];
  if (!t) return skill;
  const desc = t.desc2 ? t.desc + " · " + t.desc2 : t.desc;
  return Object.assign({}, skill, {
    nameTh: t.th || "",
    descTh: desc || "",
    use: t.use || "",
    tag: t.tag || "",
    star: !!t.star,
  });
}

/** ตัวไหนยังไม่ได้แปล — ใช้เตือนตัวเองตอนเครื่องมีสกิลเพิ่ม */
function untranslated(list) {
  return list.filter((s) => !TH[s.id]).map((s) => s.id);
}

module.exports = { TH, decorate, untranslated };
